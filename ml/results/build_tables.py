"""Render ml/results/RESULTS_TABLES.md from versions.yaml and results_cache.json.

  conda run -n ML modal run ml/modal_app/collect_results.py   # refresh the cache from the volume
  conda run -n ML python ml/results/build_tables.py           # write RESULTS_TABLES.md

Every table is rebuilt from scratch, so a registered version can never be missing from one. Blank
cells mean the eval was not run (never a guess). Sections: current status, leaderboard on the
current eval sets (labelling guideline v2), per quant, per language, errors, training, training
data, and a legacy appendix on the older eval sets.
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "ml/results"
SPLITS = ROOT / "ml/datasets/splits"
LANGS = ["banglish", "bangla", "english", "mixed"]
SET_DOC = {
    "test_clean_v2": "Gemini-written held-out messages (4 languages), gold = Opus and Sonnet agreeing under guideline v2",
    "numbers_clean_v2": "held-out messages with every amount in words, gold as above",
    "small_amounts_v2": "held-out messages with a 1 to 9 taka item, gold as above",
    "test_clean": "the same messages, gold = Gemini 3.8 Flash and Sonnet agreeing under guideline v1",
    "numbers_clean": "number-word set, guideline v1 gold",
    "small_amounts": "1 to 9 taka set, template labels (guideline v1)",
    "test": "held-out Gemini messages with Gemini's original labels (inconsistent, ~14% break the guideline)",
    "numbers": "number-word set with the Codex templates' original labels",
}


def pct(x) -> str:
    return "" if x is None else f"{100 * x:.1f}"


class Data:
    def __init__(self):
        self.reg = yaml.safe_load((RES / "versions.yaml").read_text())
        self.cache = json.loads((RES / "results_cache.json").read_text())
        self.versions = self.reg["versions"]

    def run(self, v, key):
        return self.cache.get(v[key], {})

    def bf16(self, v, split):
        return self.run(v, "run").get("bf16", {}).get(split)

    def gguf(self, v, quant, split):
        return self.run(v, "gguf_run").get("gguf", {}).get(f"{quant}|{split}")

    def size(self, v, quant):
        for k, g in self.run(v, "gguf_run").get("gguf", {}).items():
            if k.startswith(quant + "|") and g.get("file_mb"):
                return g["file_mb"]
        return None

    def has_any(self, v, splits):
        return any(self.bf16(v, s) or any(self.gguf(v, q, s) for q in self.reg["quants"]) for s in splits)


def table(head: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join("" if c is None else str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def bold_best(rows: list[list[str]], cols: range) -> list[list[str]]:
    for c in cols:
        vals = [float(r[c]) for r in rows if r[c] not in ("", None)]
        if len(vals) < 2:
            continue
        best = max(vals)
        for r in rows:
            if r[c] not in ("", None) and float(r[c]) == best:
                r[c] = f"**{r[c]}**"
    return rows


def main() -> None:
    d = Data()
    cur, leg, quants = d.reg["current_eval"], d.reg["legacy_eval"], d.reg["quants"]
    by_label = {v["label"]: v for v in d.versions}
    app, best = by_label[d.reg["app"]], by_label[d.reg["best"]]
    out = ["# Hishab results tables",
           "",
           "Generated by `ml/results/build_tables.py` from `versions.yaml` and the eval files on the Modal "
           "volume (`results_cache.json`). Do not edit by hand: add a version to `versions.yaml`, refresh the "
           "cache, rerun the script. The story of each version is in `EXPERIMENTS.md`.",
           "",
           "Scores are **exact match**: the message's set of (amount, category, type) equals the gold. "
           "bf16 = full precision on Modal (HF transformers, greedy); GGUF = llama.cpp at kiln's commit, "
           "the phone path. Blank = not run.",
           ""]

    # 1. status
    out += ["## Current status", ""]
    rows = []
    for role, v in (("in the app", app), ("best", best)):
        q = v.get("app_quant", "Q4_K_M-imat")
        cells = [pct((d.gguf(v, q, s) or {}).get("all", {}).get("exact_match")) for s in cur]
        rows.append([role, f"{v['label']} ({q}, {d.size(v, q) or '?'} MB)", *cells, v.get("change", "")])
    out += [table(["", "model", *cur, "what it added"], rows), ""]

    # 2. leaderboard on current sets
    out += ["## Leaderboard on the current eval sets (labelling guideline v2)", "",
            "\n".join(f"- `{s}`: {SET_DOC[s]}" for s in cur), ""]
    vs = [v for v in d.versions if d.has_any(v, cur)]
    rows = []
    for v in vs:
        r = [v["label"], v.get("status", "")]
        for s in cur:
            r.append(pct((d.bf16(v, s) or {}).get("all", {}).get("exact_match")))
            r.append(pct((d.gguf(v, "Q4_K_M-imat", s) or {}).get("all", {}).get("exact_match")))
        rows.append(r)
    head = ["version", "status"] + [f"{s} {k}" for s in cur for k in ("bf16", "Q4_K_M-imat")]
    out += [table(head, bold_best(rows, range(2, len(head)))), ""]

    # 3. per quant
    out += ["## Per quant, current eval sets", "", "The app ships Q4_K_M-imat. File sizes (MB):", ""]
    srows = [[v["label"]] + [str(d.size(v, q) or "") for q in quants] for v in vs]
    out += [table(["version"] + quants, srows), ""]
    for s in cur:
        rows = []
        for v in vs:
            r = [v["label"], pct((d.bf16(v, s) or {}).get("all", {}).get("exact_match"))]
            r += [pct((d.gguf(v, q, s) or {}).get("all", {}).get("exact_match")) for q in quants]
            if any(r[2:]):
                rows.append(r)
        head = ["version", "bf16"] + quants
        out += [f"### {s}", "", table(head, bold_best(rows, range(1, len(head)))), ""]

    # 4. per language
    out += ["## Per language, current eval sets", "", "Exact match per language; row counts in the header.", ""]
    for s in cur:
        n = None
        rows = []
        for v in vs:
            for path, m in (("bf16", d.bf16(v, s)), ("Q4_K_M-imat", d.gguf(v, "Q4_K_M-imat", s))):
                if not m:
                    continue
                bl = m["by_language"]
                n = n or {l: bl[l]["n"] for l in LANGS if l in bl}
                rows.append([v["label"], path] + [pct(bl[l]["exact_match"]) if l in bl else "" for l in LANGS])
        if rows:
            head = ["version", "path"] + [f"{l} ({(n or {}).get(l, '?')})" for l in LANGS]
            out += [f"### {s}", "", table(head, rows), ""]

    # 5. errors
    out += ["## Wrong messages by first failing field, current eval sets", "",
            "count = wrong number of entries; amount = a wrong amount; type = income/expense flipped; "
            "category = everything else right but a category. Swaps are gold to model.", ""]
    for s in cur:
        rows = []
        for v in vs:
            for path, e in (("bf16", d.run(v, "run").get("errors_bf16", {}).get(s)),
                            ("Q4_K_M-imat", d.run(v, "gguf_run").get("errors_gguf", {}).get(s))):
                if e:
                    rows.append([v["label"], path, f"{e['wrong']} of {e['n']}", str(e["count"]), str(e["amount"]),
                                 str(e["type"]), str(e["category"]), ", ".join(f"{a} {b}" for a, b in e["swaps"])])
        if rows:
            out += [f"### {s}", "", table(["version", "path", "wrong", "count", "amount", "type", "category", "top swaps"], rows), ""]

    # 5b. hand measurements (versions.yaml `measurements`)
    out += ["## Phone measurements (hand-recorded in versions.yaml)", "",
            "Not from the eval pipeline: Pixel 8 speed (kiln) and the 20 spoken-amount probes "
            "(`ml/datasets/probes_numbers.jsonl` through kiln-cli on the Mac, `ml/scripts/probe_gguf.py`). "
            "Per-probe detail is in EXPERIMENTS.md.", ""]
    rows = []
    for v in d.versions:
        m = v.get("measurements") or {}
        if not m:
            continue
        tok = ", ".join(f"{q} {x}" for q, x in (m.get("pixel_tok_s") or {}).items()) or m.get("pixel_speedup", "")
        probes = ", ".join(f"{q} {x}" for q, x in (m.get("probes") or {}).items())
        rows.append([v["label"], tok, m.get("pixel_how", ""), probes, m.get("notes", "")])
    out += [table(["version", "Pixel 8 generation (tok/s)", "how", "probes", "notes"], rows), ""]

    # 6. training
    out += ["## Training", "", "Best epoch is the lowest validation loss; v11 on, losses are per token of the shorter pipe answer.", ""]
    rows = []
    for v in d.versions:
        rr = d.run(v, "run")
        m, tl = rr.get("meta") or {}, rr.get("train_log") or {}
        vl = tl.get("val_loss") or []
        best_ep = (vl.index(min(vl)) + 1) if vl else ""
        if v.get("training"):  # registry override: runs whose eval_hf.json carries another run's metadata
            rows.append([v["label"], v.get("date", "") or "", "", "", "", "", "", v.get("train_split", "") or "", v["training"]])
            continue
        ep = m.get("epochs")
        rows.append([v["label"], v.get("date", "") or "", m.get("tune") or "", f"{ep:g}" if ep else "", str(best_ep),
                     " / ".join(f"{x:.4f}".lstrip("0") for x in vl), f"{m['train_rows']:,}" if m.get("train_rows") else "",
                     v.get("train_split", "") or "", f"{round(m['train_time_s'] / 60)} min" if (m.get("train_time_s") or 0) >= 60 else ""])
    out += [table(["version", "date", "tune", "epochs", "best epoch", "val loss by epoch", "train rows", "train file", "time / note"], rows), ""]

    # 7. training data
    out += ["## Training data", "", "From the local split files (versions whose split was not saved are left out).", ""]
    seen, src_rows, lang_rows = set(), {}, []
    for v in d.versions:
        sp = v.get("train_split")
        if not sp or sp in seen or not (SPLITS / f"{sp}.jsonl").exists():
            continue
        seen.add(sp)
        rows_ = [json.loads(l) for l in (SPLITS / f"{sp}.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
        src_rows[v["label"]] = Counter(r.get("source", "") for r in rows_)
        lang = Counter(r["language"] for r in rows_)
        per = Counter(min(len(r["transactions"]), 4) for r in rows_)
        lang_rows.append([v["label"], sp, f"{len(rows_):,}"] + [f"{lang[l]:,}" for l in LANGS] +
                         [f"{per[k]:,}" for k in range(5)] + [v.get("dataset", "") or ""])
    out += [table(["first version", "file", "rows", *LANGS, "0 tx", "1 tx", "2 tx", "3 tx", "4+ tx", "HF dataset"], lang_rows), ""]
    sources = sorted({s for c in src_rows.values() for s in c}, key=lambda s: -max(c.get(s, 0) for c in src_rows.values()))
    out += [table(["source"] + list(src_rows), [[s] + [f"{c.get(s, 0):,}" if c.get(s) else "" for c in src_rows.values()] for s in sources]), ""]

    # 8. legacy
    out += ["## Legacy appendix: older eval sets", "",
            "These sets use older labelling conventions; a newer model can score lower on them by following "
            "guideline v2 (see EXPERIMENTS.md, v13). Use them to compare old versions with each other.", "",
            "\n".join(f"- `{s}`: {SET_DOC[s]}" for s in leg), ""]
    for s in leg:
        rows = []
        for v in d.versions:
            r = [v["label"], pct((d.bf16(v, s) or {}).get("all", {}).get("exact_match"))]
            r += [pct((d.gguf(v, q, s) or {}).get("all", {}).get("exact_match")) for q in ["F16", "Q8_0", "Q6_K", "Q5_K_M", "Q4_K_M-imat", "Q4_0-imat"]]
            if any(r[1:]):
                rows.append(r)
        if rows:
            out += [f"### {s}", "", table(["version", "bf16", "F16", "Q8_0", "Q6_K", "Q5_K_M", "Q4_K_M-imat", "Q4_0-imat"], rows), ""]

    (RES / "RESULTS_TABLES.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote ml/results/RESULTS_TABLES.md ({len(out)} lines, {len(d.versions)} versions)")


if __name__ == "__main__":
    main()
